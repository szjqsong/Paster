import AppKit
import ImageIO
import Vision

/// Raw data pulled off the pasteboard on the main thread; classified on a background queue.
struct RawCapture {
    var fileURLs: [URL] = []
    var string: String?
    var png: Data?
    var tiff: Data?
    var rtf: Data?
    var html: Data?
    var bundleID: String?
    var appName: String?
    var recognizeText = false
}

final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    /// Pasteboard marker types used by password managers and other apps to flag content
    /// that clipboard managers should not record (see nspasteboard.org).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]

    static let maxTextBytes = 4 * 1024 * 1024
    static let maxRichBytes = 4 * 1024 * 1024

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount = 0
    private let workQueue = DispatchQueue(label: "paster.capture", qos: .userInitiated)

    func start() {
        lastChangeCount = pasteboard.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call right after Paster itself writes to the pasteboard so that write is not re-recorded.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let settings = Settings.shared
        guard !settings.paused else { return }
        guard let types = pasteboard.types, !types.isEmpty else { return }

        if settings.ignoreConcealed {
            let raw = Set(types.map(\.rawValue))
            if !raw.isDisjoint(with: ClipboardMonitor.ignoredTypes) { return }
        }

        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, settings.excludedBundleIDs.contains(bid) { return }

        var raw = RawCapture()
        raw.bundleID = front?.bundleIdentifier
        raw.appName = front?.localizedName
        raw.recognizeText = settings.recognizeTextInImages
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL] {
            raw.fileURLs = urls
        }
        if raw.fileURLs.isEmpty {
            raw.string = pasteboard.string(forType: .string)
            let hasText = !(raw.string ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            if hasText {
                raw.rtf = pasteboard.data(forType: .rtf)
                raw.html = pasteboard.data(forType: .html)
            } else {
                raw.png = pasteboard.data(forType: .png)
                if raw.png == nil { raw.tiff = pasteboard.data(forType: .tiff) }
            }
        }

        workQueue.async {
            guard let (item, blobs) = ClipboardMonitor.process(raw) else { return }
            DispatchQueue.main.async {
                Store.shared.insertCaptured(item, blobs: blobs)
            }
        }
    }

    // MARK: Classification (pure, testable)

    static func process(_ raw: RawCapture) -> (ClipItem, [String: Data])? {
        var blobs: [String: Data] = [:]

        if !raw.fileURLs.isEmpty {
            var item = ClipItem(kind: .file)
            item.filePaths = raw.fileURLs.map(\.path)
            item.text = raw.fileURLs.map(\.lastPathComponent).joined(separator: "\n")
            item.contentHash = Store.sha256(Data(("f:" + item.filePaths.joined(separator: "\n")).utf8))
            item.sourceBundleID = raw.bundleID
            item.sourceAppName = raw.appName
            return (item, blobs)
        }

        if let string = raw.string,
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let bytes = string.utf8.count
            guard bytes <= maxTextBytes else { return nil }
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            var item = ClipItem(kind: .text)
            item.text = string
            item.byteSize = bytes
            if ColorParser.parse(trimmed) != nil {
                item.kind = .color
                item.text = trimmed
            } else if isLink(trimmed) {
                item.kind = .link
                item.text = trimmed
            } else {
                if let rtf = raw.rtf, !rtf.isEmpty, rtf.count <= maxRichBytes {
                    blobs["rtf"] = rtf
                    item.hasRTF = true
                }
                if let html = raw.html, !html.isEmpty, html.count <= maxRichBytes {
                    blobs["html"] = html
                    item.hasHTML = true
                }
                if item.hasRTF || item.hasHTML { item.kind = .richText }
            }
            item.contentHash = Store.sha256(Data(("t:" + item.text).utf8))
            item.sourceBundleID = raw.bundleID
            item.sourceAppName = raw.appName
            return (item, blobs)
        }

        var pngData = raw.png
        if pngData == nil, let tiff = raw.tiff, let rep = NSBitmapImageRep(data: tiff) {
            pngData = rep.representation(using: .png, properties: [:])
        }
        if let png = pngData, let src = CGImageSourceCreateWithData(png as CFData, nil) {
            var item = ClipItem(kind: .image)
            if let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
                item.pixelWidth = (props[kCGImagePropertyPixelWidth] as? Int) ?? 0
                item.pixelHeight = (props[kCGImagePropertyPixelHeight] as? Int) ?? 0
            }
            guard item.pixelWidth > 0, item.pixelHeight > 0 else { return nil }
            item.byteSize = png.count
            item.contentHash = Store.sha256(png)
            item.sourceBundleID = raw.bundleID
            item.sourceAppName = raw.appName
            blobs["png"] = png
            if let thumb = makeThumbnail(source: src, maxPixel: 560) {
                blobs["thumb.png"] = thumb
            }
            if raw.recognizeText, let cg = CGImageSourceCreateImageAtIndex(src, 0, nil) {
                item.text = recognizeText(in: cg)
            }
            return (item, blobs)
        }
        return nil
    }

    /// On-device OCR (Vision) so images can be found by the text they contain.
    static func recognizeText(in image: CGImage) -> String {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        request.automaticallyDetectsLanguage = true
        let handler = VNImageRequestHandler(cgImage: image, options: [:])
        guard (try? handler.perform([request])) != nil else { return "" }
        let lines = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }
        return String(lines.joined(separator: "\n").prefix(20_000))
    }

    static func isLink(_ s: String) -> Bool {
        guard s.count <= 2048,
              s.rangeOfCharacter(from: .whitespacesAndNewlines) == nil,
              let url = URL(string: s),
              let scheme = url.scheme?.lowercased() else { return false }
        if scheme == "mailto" { return s.contains("@") }
        guard ["http", "https", "ftp"].contains(scheme) else { return false }
        return !(url.host ?? "").isEmpty
    }

    static func makeThumbnail(source: CGImageSource, maxPixel: Int) -> Data? {
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, opts as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])
    }
}
